import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import test from 'node:test';
import {PGlite} from '@electric-sql/pglite';
test('certificate verification preserves privacy; revocation is authorized, audited and irreversible',async(t)=>{
 const db=new PGlite();t.after(()=>db.close());
 const read=name=>readFile(new URL(name,import.meta.url),'utf8');
 await db.exec(await read('./local_bootstrap.sql'));
 await db.exec((await read('../migrations/initialize_production.sql')).replace('CREATE EXTENSION IF NOT EXISTS pgcrypto;',''));
 await db.exec(await read('../migrations/upgrade_existing_database.sql'));
 const organizer='a0000000-0000-0000-0000-000000000001',attendee='a0000000-0000-0000-0000-000000000002',stranger='a0000000-0000-0000-0000-000000000003',conf='b0000000-0000-0000-0000-000000000001';
 await db.query('INSERT INTO auth.users(id) VALUES($1),($2),($3)',[organizer,attendee,stranger]);
 await db.query("UPDATE profiles SET role='organizer' WHERE id=$1",[organizer]);
 await db.query("INSERT INTO conferences(id,title,organizer_id,start_date,end_date,status) VALUES($1,'Verified conference',$2,now()-interval '2 days',now()-interval '1 day','completed')",[conf,organizer]);
 await db.query('INSERT INTO participants(conference_id,user_id,attended) VALUES($1,$2,true)',[conf,attendee]);
 const asUser=async(id,role='authenticated')=>{await db.exec('RESET ROLE');await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('SET ROLE '+role);};
 await asUser(organizer);
 await db.query("SELECT issue_certificates_bulk($1,'attendance',$2)",[conf,[attendee]]);
 const cert=(await db.query('SELECT * FROM certificates')).rows[0];
 await db.exec('RESET ROLE');
 const path=attendee+'/'+cert.id+'.pdf';
 await db.query('UPDATE certificates SET pdf_path=$1 WHERE id=$2',[path,cert.id]);
 await db.query("INSERT INTO storage.objects(bucket_id,name) VALUES('certificate-pdfs',$1)",[path]);
 await asUser('','anon');
 const visible=(await db.query('SELECT * FROM verify_certificate($1::uuid)',[cert.verification_token])).rows[0];
 assert.deepEqual(Object.keys(visible).sort(),['certificate_number','certificate_type','conference_title','issued_at','revoked_at'].sort());
 assert.equal(visible.revoked_at,null);
 await asUser(stranger);
 await assert.rejects(db.query("SELECT write_audit_log('fake','certificate',$1,'{}'::jsonb)",[cert.id]),/permission denied/);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM certificates')).rows[0].n,0);
 await assert.rejects(db.query('SELECT revoke_certificate($1,$2)',[cert.id,'Unauthorized attempt']),/không có quyền/);
 await asUser(attendee);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM storage.objects WHERE name=$1',[path])).rows[0].n,1);
 await asUser(organizer);
 await assert.rejects(db.query('SELECT revoke_certificate($1,$2)',[cert.id,'']),/lý do/);
 assert.equal((await db.query('SELECT revoke_certificate($1,$2) AS changed',[cert.id,'Recipient requested correction'])).rows[0].changed,true);
 assert.equal((await db.query('SELECT revoke_certificate($1,$2) AS changed',[cert.id,'Recipient requested correction'])).rows[0].changed,false);
 await db.exec('RESET ROLE');
 assert.equal((await db.query("SELECT count(*)::int AS n FROM audit_logs WHERE action='certificate.revoked' AND entity_id=$1",[cert.id])).rows[0].n,1);
 await assert.rejects(db.query('UPDATE certificates SET revoked_at=NULL WHERE id=$1',[cert.id]),/không được khôi phục/);
 await assert.rejects(db.query("UPDATE certificates SET certificate_number='FAKE' WHERE id=$1",[cert.id]),/không được thay đổi/);
 await asUser(attendee);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM storage.objects WHERE name=$1',[path])).rows[0].n,0);
 await asUser('','anon');
 assert.ok((await db.query('SELECT * FROM verify_certificate($1::uuid)',[cert.verification_token])).rows[0].revoked_at);
 assert.equal((await db.query('SELECT * FROM verify_certificate($1::text)',[cert.certificate_number])).rows.length,0);
});
